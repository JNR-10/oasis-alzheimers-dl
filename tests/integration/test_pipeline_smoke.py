"""The whole pipeline, end to end, small enough to run on every push.

The other end-to-end tests are `slow`, and CI excludes `slow` — so until this module
existed, CI never verified the claim the pipeline is built on: that a cohort goes in and
a results table comes out. Green CI was evidence that the pieces worked, never that they
composed.

This is the composition, at a size that costs seconds: cohort -> sequences -> a
subject-level split drawn once and written to the manifest -> training -> a threshold
chosen on validation -> one read of the test partition -> a run record -> a results
table regenerated by the report command. It asserts *wiring*, not learning: 16 synthetic
subjects cannot support a claim about ROC-AUC, and asserting one would be asserting noise.
"""

from __future__ import annotations

from pathlib import Path

import pandas as pd
import pytest
import torch
from torch.utils.data import DataLoader

from oasis_dl.cli.report import main as report_main
from oasis_dl.data.cohort import build_sequences
from oasis_dl.data.dataset import VisitSequenceDataset, single_scan_collate
from oasis_dl.data.manifest import read_manifest, write_manifest
from oasis_dl.data.splits import (
    assign_sequences,
    check_no_leakage,
    partition_subjects,
    subject_label,
)
from oasis_dl.data.synthetic import SyntheticCohort, SyntheticCohortSpec
from oasis_dl.evaluation.bootstrap import bootstrap_metrics
from oasis_dl.evaluation.metrics import compute_metrics, select_threshold
from oasis_dl.evaluation.reporting import write_run_results
from oasis_dl.models.arms import SingleScanModel
from oasis_dl.models.encoder import VisitEncoder
from oasis_dl.models.heads import ClassificationHead
from oasis_dl.training.loop import TrainingConfig, evaluate_split, pos_weight_from_labels, train
from oasis_dl.training.losses import CombinedObjective
from oasis_dl.training.seed import seed_everything
from oasis_dl.types import Partition, Visit
from oasis_dl.utils.provenance import RunProvenance

DIM = 16
CPU = torch.device("cpu")


def _manifest_frame(visits: list[Visit], assignment: dict[str, Partition]) -> pd.DataFrame:
    """One row per session, carrying the partition its subject was drawn into."""
    return pd.DataFrame(
        [
            {
                "subject_id": str(v.subject_id),
                "session_id": str(v.session_id),
                "partition": assignment[str(v.subject_id)].value,
                "days_from_entry": v.days_from_entry,
                "scan_path": str(v.scan_path),
                "label": None if v.label is None else int(v.label),
                "is_target_visit": v.label is not None,
                "exclusion_reason": "",
            }
            for v in visits
        ]
    )


@pytest.mark.parametrize(
    ("backbone", "volume_shape"),
    [("resnet10", (8, 8, 8)), ("vit_tiny_8", (16, 16, 16))],
)
def test_a_cohort_becomes_a_results_table(
    tmp_path: Path, backbone: str, volume_shape: tuple[int, int, int]
) -> None:
    seed_everything(11, deterministic=False)

    # --- cohort -------------------------------------------------------------------
    cohort = SyntheticCohort(
        root=tmp_path / "cohort",
        spec=SyntheticCohortSpec(
            n_subjects=16,
            max_visits=2,
            impaired_fraction=0.35,
            unlabeled_fraction=0.0,
            volume_shape=volume_shape,
            seed=20261124,
        ),
    ).generate()
    visits = cohort.visits()
    sequences = build_sequences(visits, max_length=3)

    # --- split, drawn once and written down (#6, ADR-0001) ------------------------
    labels = {
        subject: subject_label([s for s in sequences if s.subject_id == subject])
        for subject in {s.subject_id for s in sequences}
    }
    assignment = partition_subjects(labels, ratios=(0.5, 0.25, 0.25), seed=42)

    manifest = tmp_path / "data" / "manifest.csv"
    write_manifest(_manifest_frame(visits, {str(k): v for k, v in assignment.items()}), manifest)
    recorded = read_manifest(manifest)
    assert {row.subject_id: row.partition for row in recorded.itertuples()} == {
        str(subject): partition.value for subject, partition in assignment.items()
    }, "the partition read back from the manifest is not the partition that was drawn"
    # "Drawn once": the record cannot be silently replaced by a second draw.
    with pytest.raises(FileExistsError):
        write_manifest(
            _manifest_frame(visits, {str(k): v for k, v in assignment.items()}), manifest
        )

    grouped = assign_sequences(sequences, assignment)
    check_no_leakage(grouped)

    # --- train, choose a threshold, read the test partition once ------------------
    def loader(partition: Partition) -> DataLoader[object]:
        training = partition is Partition.TRAIN
        return DataLoader(
            VisitSequenceDataset(grouped[partition], seed=0),
            batch_size=2,
            shuffle=training,
            drop_last=training,
            collate_fn=single_scan_collate,
        )

    model = SingleScanModel(
        VisitEncoder(backbone=backbone, embedding_dim=DIM, volume_shape=volume_shape),
        ClassificationHead(embedding_dim=DIM),
    )
    run_dir = tmp_path / "experiments" / "baseline_single_scan_seed11"
    best = train(
        model=model,
        train_loader=loader(Partition.TRAIN),
        val_loader=loader(Partition.VAL),
        objective=CombinedObjective(
            pos_weight=pos_weight_from_labels([int(s.label) for s in grouped[Partition.TRAIN]])
        ),
        config=TrainingConfig(max_epochs=1, batch_size=2, mixed_precision=False, seed=11),
        output_dir=run_dir,
        device=CPU,
        provenance=RunProvenance(
            run_id="smoke",
            experiment="baseline_single_scan",
            git_commit="c" * 40,
            git_dirty=False,
            seed=11,
            timestamp="2026-11-24T00:00:00+00:00",
            manifest_path=str(manifest),
            python_version="3.11.0",
            platform="test",
        ),
    )
    assert best.exists() and (run_dir / "provenance.json").exists()

    val_labels, val_scores, _ = evaluate_split(model, loader(Partition.VAL), CPU)
    threshold = select_threshold(val_labels, val_scores)
    test_labels, test_scores, test_subjects = evaluate_split(model, loader(Partition.TEST), CPU)
    metrics = compute_metrics(test_labels, test_scores, threshold=threshold)

    write_run_results(
        run_dir,
        arm="B1",
        partition="test",
        metrics=metrics,
        n_subjects=len(set(test_subjects)),
        n_visits=len(test_labels),
        intervals=bootstrap_metrics(
            test_labels,
            test_scores,
            test_subjects,
            threshold=threshold,
            metrics=("roc_auc",),
            n_resamples=20,
            seed=11,
        ),
    )

    # --- the table, regenerated by the command (#12) ------------------------------
    out = tmp_path / "results" / "results"
    assert report_main(["--runs", str(tmp_path / "experiments"), "--out", str(out)]) == 0
    row = pd.read_csv(out.with_suffix(".csv")).query("arm == 'B1' and metric == 'roc_auc'").iloc[0]

    # Cohort size, metric with interval, seed count and commit — #12's four.
    assert row["n_subjects"] == len(set(test_subjects))
    assert row["interval_kind"] == "bootstrap"
    assert row["n_seeds"] == 1
    assert row["commit"] == "c" * 7
    # Every number traces to the run, not to this test.
    assert row["point"] == pytest.approx(metrics.roc_auc)
    assert row["n_subjects"] == metrics.n or row["n_visits"] == metrics.n
